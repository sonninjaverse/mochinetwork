// Copies the algorithm sources into the app so the picker can show exactly what
// is running. Bundling beats fetching from an explorer: it cannot fail on
// stage, and it works before anything is verified.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const SRC = "../contracts/src/algorithms";
const OUT = "src/social/lib/generated";

mkdirSync(OUT, { recursive: true });

const sources = {};
for (const file of readdirSync(SRC)) {
  if (!file.endsWith(".sol")) continue;
  sources[file.replace(".sol", "")] = readFileSync(join(SRC, file), "utf8");
}

writeFileSync(
  join(OUT, "sources.ts"),
  "// Generated by scripts/bundle-sources.mjs. Do not edit.\n" +
    `export const ALGORITHM_SOURCES: Record<string, string> = ${JSON.stringify(sources, null, 2)};\n`,
);

console.log(`Bundled ${Object.keys(sources).length} algorithm sources`);
